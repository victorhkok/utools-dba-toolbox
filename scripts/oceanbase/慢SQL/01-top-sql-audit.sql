-- Top SQL（GV$OB_SQL_AUDIT）
-- 适用版本：4.x
-- 风险：只读
-- 说明：SQL Audit
-- 备注：MySQL 模式用 LIMIT 20，Oracle 模式用 FETCH FIRST 20 ROWS ONLY，GV$OB_SQL_AUDIT 列名需在 OB 4.x 实测核对。

SELECT SQL_ID, SQL_TEXT, ELAPSED_TIME, EXECUTIONS
FROM oceanbase.GV$OB_SQL_AUDIT
WHERE ELAPSED_TIME > 0
ORDER BY ELAPSED_TIME DESC LIMIT 20;
