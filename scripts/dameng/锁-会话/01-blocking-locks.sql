-- 阻塞锁 / 会话
-- 适用版本：DM8+
-- 风险：只读
-- 说明：V$LOCK / V$SESSIONS
-- 备注：V$LOCK/V$SESSIONS 的阻塞标志列名需在 DM8 实测核对，如无 BLOCKED 列请改查 V$LOCK 全量。

SELECT TOP 20 L.SESS_ID AS BLOCKED_SESS, L.TRX_ID, S.USERNAME, S.CLIENT_IP, S.SQL_TEXT
FROM V$LOCK L JOIN V$SESSIONS S ON L.SESS_ID = S.SESS_ID
WHERE L.BLOCKED = 1
ORDER BY L.SESS_ID;
