-- 统计信息 / ANALYZE
-- 适用版本：6.x+
-- 风险：谨慎
-- 说明：ANALYZE TABLE
-- 备注：TiDB 的 ANALYZE 与 MySQL 兼容，生产建议非高峰执行。

-- 先确认表与统计信息时间（只读）：
SELECT TABLE_SCHEMA, TABLE_NAME, UPDATE_TIME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = '<SCHEMA>' ORDER BY UPDATE_TIME ASC LIMIT 20;
